const viewIds = new Set<string>();
for (const view of views) {
  if (viewIds.has(view.id)) throw new Error(`duplicate view ${view.id}`);
  viewIds.add(view.id);
  const seen = new Set<string>();
  for (const slot of view.groups.flatMap((group) => group.slots)) {
    if (!ids.has(slot.id)) throw new Error(`${view.id} missing ${slot.id}`);
    if (seen.has(slot.id)) throw new Error(`${view.id} repeats ${slot.id}`);
    seen.add(slot.id);
  }
}

